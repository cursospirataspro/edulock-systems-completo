test('stream operation reservation and advisory locks persist across concurrent callers', async () => {
    const courseId = await course(), operationId = id('operations');
    const input = { id: operationId, actorKey: 'admin', courseId, title: 'Synthetic', fileSize: 12, fileSha256: hash('synthetic') };
    const rows = await Promise.all([db.reserveStreamOperation(input), db.reserveStreamOperation(input)]);
    assert.equal(rows[0].id, rows[1].id);
    await db.reserveStreamOperation({ ...input, actorKey: 'producer:other', title: 'Different' });
    assert.equal((await db.getStreamOperation(operationId)).actor_key, 'admin');
    let unlock, entered;
    const gate = new Promise(resolve => { unlock = resolve; });
    const ready = new Promise(resolve => { entered = resolve; });
    const key = `synthetic-${crypto.randomUUID()}`;
    const running = db.withStreamLock(key, async () => { entered(); await gate; return true; });
    await ready;
    try { await assert.rejects(db.withStreamLock(key, async () => false), { code: 'STREAM_BUSY' }); }
    finally { unlock(); }
    assert.equal(await running, true);
    assert.equal(await db.withStreamLock(key, async () => true), true);
});

