test('producer revocation is isolated, audited once and immediately denies its course while another course stays usable', async () => {
    const owner = await producer({ maxLicenses: 0 }), other = await producer(), user = await student(), device = crypto.randomUUID();
    const courseA = await course(owner), courseB = await course(owner), serialA = await license(courseA, { producerId: owner }), serialB = await license(courseB, { producerId: owner });
    const videoA = id('videos'), videoB = id('videos');
    for (const [videoId, courseId] of [[videoA, courseA], [videoB, courseB]]) await db.addToCatalog({ videoId, courseId, producerId: owner, title: 'Synthetic revocation test', status: 'ready' });
    assert.equal((await db.claimAndActivateLicenseAtomic(activationInput(serialA.hash, user, device))).ok, true);
    assert.equal((await db.claimAndActivateLicenseAtomic(activationInput(serialB.hash, user, device))).ok, true);
    const policy = createAccessPolicy({ db }), claims = { sub: user, deviceId: device };
    await policy.authorizeVideo(claims, videoA, device);
    await policy.authorizeVideo(claims, videoB, device);
    await assert.rejects(db.revokeProducerLicense({ producerId: other, licenseId: serialA.id }), { code: 'LICENSE_NOT_FOUND' });
    assert.equal((await db.getLicenseById(serialA.id)).status, 'active');
    assert.equal((await db.revokeProducerLicense({ producerId: owner, licenseId: serialA.id })).alreadyRevoked, false);
    assert.equal((await db.revokeProducerLicense({ producerId: owner, licenseId: serialA.id })).alreadyRevoked, true);
    await assert.rejects(policy.authorizeVideo(claims, videoA, device), { code: 'LICENSE_REQUIRED' });
    await policy.authorizeVideo(claims, videoB, device);
    assert.equal((await db.getLicenseById(serialB.id)).status, 'active');
    assert.equal(await db.countActiveActivationsByLicense(serialA.id), 0);
    assert.equal(await db.countActiveActivationsByLicense(serialB.id), 1);
    assert.equal(await db.countProducerLicenses(owner), 2, 'revocation never refunds the generation quota');
    const audits = (await db.pool.query("SELECT metadata FROM suspicious_activity WHERE student_id=$1 AND type='producer_license_revoked'", [user])).rows;
    assert.equal(audits.length, 1); assert.equal(JSON.parse(audits[0].metadata).licenseId, serialA.id);
    const visible = await db.getProducerLicenseItems({ producerId: owner });
    assert.equal(visible.total, 2); assert.equal(visible.rows.every(row => !('license_key_hash' in row)), true);
    assert.equal((await db.getProducerLicenseItems({ producerId: other })).total, 0);
});

test('producer batches are permanent: expiry is refused, stored dates never block playback or claims, lots report no expired count', async () => {
    const owner = await producer({ maxLicenses: 0 }), courseId = await course(owner), user = await student(), device = crypto.randomUUID();
    const expiresAt = new Date(Date.now() + 30 * 60 * 1000).toISOString(), lotId = id('lots');
    const serials = Array.from({ length: 2 }, () => { const value = id('licenses'); return { id: value, hash: hash(value) }; });
    await assert.rejects(db.createProducerLotAtomic({ producerId: owner, lot: { id: lotId, courseId, maxDevices: 1, expiresAt }, licenses: serials }), { code: 'LICENSE_EXPIRY_UNSUPPORTED' });
    await assert.rejects(db.createProducerLotAtomic({ producerId: owner, lot: { id: lotId, courseId, maxDevices: 1, durationDays: 30 }, licenses: serials }), { code: 'LICENSE_EXPIRY_UNSUPPORTED' });
    assert.equal((await db.createProducerLotAtomic({ producerId: owner, lot: { id: lotId, courseId, maxDevices: 1 }, licenses: serials })).ok, true);
    assert.equal((await db.getLicenseById(serials[0].id)).expires_at, null);
    const activation = await db.claimAndActivateLicenseAtomic(activationInput(serials[0].hash, user, device));
    assert.equal(activation.ok, true); assert.equal((await db.getLicenseById(serials[0].id)).expires_at, null, 'activation never writes a course expiry');
    const videoId = id('videos');
    await db.addToCatalog({ videoId, courseId, producerId: owner, title: 'Synthetic permanent test', status: 'ready' });
    const policy = createAccessPolicy({ db });
    await policy.authorizeVideo({ sub: user, deviceId: device }, videoId, device);
    // A legacy stored date must not lock the student out: the right to the course is permanent.
    await db.pool.query('UPDATE licenses SET expires_at=$1 WHERE lot_id=$2 AND producer_id=$3', ['2020-01-01T00:00:00.000Z', lotId, owner]);
    await policy.authorizeVideo({ sub: user, deviceId: device }, videoId, device);
    assert.equal((await db.claimAndActivateLicenseAtomic(activationInput(serials[1].hash, user, device))).ok, true);
    const lots = await db.getLotsByProducer(owner);
    assert.equal(Number(lots[0].free_count), 0); assert.equal(Number(lots[0].used_count), 2); assert.equal(lots[0].expired_count, undefined);
});

