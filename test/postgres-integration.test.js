test('regeneration keeps commercial metadata and never unblocks an unrelated device', async () => {
    const owner = await producer(), courseId = await course(owner), user = await student(owner), lotId = id('lots');
    await db.createLot({ id: lotId, courseId, quantity: 1, producerId: owner });
    const serial = await license(courseId, { producerId: owner, lotId });
    const activation = await db.claimAndActivateLicenseAtomic(activationInput(serial.hash, user)); assert.equal(activation.ok, true);
    const order = crypto.randomUUID(); await db.pool.query('UPDATE licenses SET order_id=$1, notes=$2 WHERE id=$3', [order, 'synthetic-notes', serial.id]);
    const blockedFingerprint = crypto.randomUUID();
    await db.pool.query("INSERT INTO devices(id,student_id,fingerprint,status,first_seen,last_seen) VALUES($1,$2,$3,'blocked',$4,$4)",
        [crypto.randomUUID(), user, blockedFingerprint, new Date().toISOString()]);
    const newId = id('licenses'), newKey = 'ABCD-EFGH-JKLM-' + crypto.randomBytes(2).toString('hex').toUpperCase().replace(/[01]/g, '2');
    const previousSecret = process.env.JWT_SECRET;
    if (!process.env.JWT_SECRET || process.env.JWT_SECRET.length < 32) process.env.JWT_SECRET = crypto.randomBytes(32).toString('hex');
    let result;
    try {
        result = await db.regenerateLicense({ oldLicenseId: serial.id, newLicenseId: newId, newLicenseKey: newKey,
            newLicenseKeyHash: crypto.createHmac('sha256', process.env.JWT_SECRET).update(newKey).digest('hex') });
    } finally {
        if (previousSecret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = previousSecret;
    }
    assert.equal(result.ok, true); const regenerated = await db.getLicenseById(newId);
    assert.equal(regenerated.producer_id, owner); assert.equal(regenerated.lot_id, lotId); assert.equal(regenerated.order_id, order); assert.equal(regenerated.notes, 'synthetic-notes');
    const blocked = (await db.pool.query('SELECT status FROM devices WHERE student_id=$1 AND fingerprint=$2', [user, blockedFingerprint])).rows[0];
    assert.equal(blocked.status, 'blocked'); assert.equal(await db.countActiveActivationsByLicense(serial.id), 0);
});

