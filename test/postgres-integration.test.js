async function student(producerId = null) {
    const value = id('students');
    await db.createStudent({ id: value, email: `qa-${value}@example.invalid`, studentId: `qa-${value}`, name: 'Synthetic QA', active: true, allowedVideos: [] });
    await db.pool.query("UPDATE students SET approval_status='approved', max_devices=3, producer_id=$1 WHERE id=$2", [producerId, value]);
    return value;
}
async function producer({ maxLicenses = 10, maxDevices = 2, maxStudents = 0 } = {}) {
    const value = id('producers');
    await db.createProducer({ id: value, email: `qa-${value}@example.invalid`, passwordHash: hash('synthetic-qa-only'), name: 'Synthetic QA', maxLicenses, maxDevices, maxStudents });
    return value;
}
async function course(producerId = null) {
    const value = id('courses'); await db.createCourse({ id: value, name: 'Synthetic QA course', producerId }); return value;
}
async function moduleFor(courseId, parentId = null) {
    const value = id('modules'); await db.createModule({ id: value, courseId, parentId, name: 'Synthetic QA module' }); return value;
}
async function license(courseId, { producerId = null, studentId = null, maxDevices = 1, lotId = null } = {}) {
    const value = id('licenses'), licenseKeyHash = hash(value);
    if (studentId) await db.createLicense({ id: value, licenseKeyHash, studentId, courseId, maxDevices });
    else await db.createFreeLicense({ id: value, licenseKeyHash, courseId, maxDevices, producerId, lotId });
    return { id: value, hash: licenseKeyHash };
}
function activationInput(licenseHash, studentId, deviceId = crypto.randomUUID()) {
    return { licenseKeyHash: licenseHash, studentId, deviceId, activationTokenHash: hash(crypto.randomUUID()), maxAllowed: 3,
        expiresAt: new Date(Date.now() + 60 * 60 * 1000).toISOString() };
}

