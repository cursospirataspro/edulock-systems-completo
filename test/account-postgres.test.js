    const account = identity(), pending = await request(account), approved = await request(account, { status: 'approved' });
    await query('UPDATE registration_requests SET requested_at=$1 WHERE id=$2', ['2999-01-01T00:00:00.000Z', approved]);
    let resolved = await db.resolveFirebaseAccount({ ...account, emailVerified: true });
    assert.equal(resolved.student, null); assert.equal(resolved.registration.id, pending);
    const rejected = await request(account, { status: 'rejected' });
    resolved = await db.resolveFirebaseAccount({ ...account, emailVerified: true });
    assert.equal(resolved.registration.id, rejected);
