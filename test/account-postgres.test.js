test('concurrent admin logins without a student row cannot exceed their device limit', async () => {
    const owner = 'admin_qa-device-' + uuid(); tracked.deviceOwners.add(owner);
    assert.equal(await row('students', owner), null);
    const firstFingerprint = uuid();
    assert.equal((await db.registerOrValidateDevice(owner, firstFingerprint, {}, 2)).ok, true);

    const original = db.pool.connect;
    // Widen the real count/insert race without faking query results. With the
    // owner lock the second count waits; without it both logins see one slot.
    db.pool.connect = async function (...args) {
        const client = await original.apply(this, args);
        return { release: () => client.release(), query: async (sql, params) => {
            const result = await client.query(sql, params);
            if (/^SELECT COUNT\(\*\) as n FROM devices/i.test(sql) && params[0] === owner) {
                await client.query('SELECT pg_sleep(0.05)');
            }
            return result;
        } };
    };
    let attempts;
    try { attempts = await Promise.all([uuid(), uuid()].map(fingerprint => db.registerOrValidateDevice(owner, fingerprint, {}, 2))); }
    finally { db.pool.connect = original; }
    assert.equal(attempts.filter(value => value.ok).length, 1);
    assert.deepEqual(attempts.find(value => !value.ok), { ok: false, device: null, reason: 'device_limit_exceeded', limit: 2, activeCount: 2 });
    assert.equal(await db.countActiveDevices(owner), 2);
    assert.equal((await db.registerOrValidateDevice(owner, firstFingerprint, {}, 2)).reason, 'existing');
    assert.equal(await row('students', owner), null, 'admin device registration must not invent a student row');
});

