async function student(account, extra = {}) {
    const value = id('students');
    await db.createStudent({ id: value, email: extra.email || account.email, studentId: 'qa-' + value, name: 'Synthetic existing account', active: extra.active !== false, allowedVideos: extra.allowedVideos || [] });
    await query('UPDATE students SET firebase_uid=$1,approval_status=$2,max_devices=$3 WHERE id=$4',
        [extra.uid === undefined ? account.uid : extra.uid, extra.status || 'approved', extra.maxDevices || 3, value]);
    return value;
}
async function course() { const value = id('courses'); await db.createCourse({ id: value, name: 'Synthetic account course' }); return value; }
async function request(account, extra = {}) {
    const deviceId = extra.deviceId || id('registrationDevices');
    tracked.registrationDevices.add(deviceId);
    const requestId = await db.createRegistrationRequest({ email: account.email, firebaseUid: account.uid, emailVerified: extra.emailVerified === true,
        deviceId, name: 'Synthetic applicant', deviceModel: 'QA device', deviceName: 'QA', ...extra });
    tracked.requests.add(requestId);
    if (extra.status) await query('UPDATE registration_requests SET status=$1 WHERE id=$2', [extra.status, requestId]);
    return requestId;
}
async function approve(input) {
    const result = await db.approveRegistrationAtomic(input);
    tracked.students.add(result.studentId);
    return result;
}
async function entitlement(studentId, courseId) {
    const licenseId = id('licenses'), activationId = id('activations');
    await db.createLicense({ id: licenseId, licenseKeyHash: uuid(), studentId, courseId, maxDevices: 3 });
    await db.createActivation({ id: activationId, licenseId, studentId, deviceId: uuid(), activationTokenHash: uuid(), expiresAt: new Date(Date.now() + 3600000).toISOString() });
    return { licenseId, activationId };
}
async function state(studentId) {
    return {
        student: await row('students', studentId),
        courses: (await query('SELECT * FROM student_courses WHERE student_id=$1 ORDER BY course_id', [studentId])).rows,
        licenses: (await query('SELECT * FROM licenses WHERE student_id=$1 ORDER BY id', [studentId])).rows,
        activations: (await query('SELECT * FROM activations WHERE student_id=$1 ORDER BY id', [studentId])).rows,
    };
}
async function accountCount(account) {
    return Number((await query('SELECT COUNT(*) AS n FROM students WHERE firebase_uid=$1 OR LOWER(TRIM(email))=$2', [account.uid, account.email])).rows[0].n);
}
async function sqlFailureAt(match, work) {
    // Inject a real PostgreSQL statement error on the transaction connection,
    // so rollback is tested in PostgreSQL without creating global triggers.
    const original = db.pool.connect;
    let injected = false;
    db.pool.connect = async function (...args) {
        const client = await original.apply(this, args);
        return { release: () => client.release(), query: async (sql, params) => {
            if (!injected && match(sql, params)) { injected = true; return client.query('SELECT 1 / 0'); }
            return client.query(sql, params);
        } };
    };
    try { await assert.rejects(work(), { code: '22012' }); assert.equal(injected, true); }
    finally { db.pool.connect = original; }
}

